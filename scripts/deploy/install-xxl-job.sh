#!/usr/bin/env bash
# 一键安装并启动 XXL-JOB Admin（systemd）
# 用法（服务器 root）：
#   bash /opt/smart-converge-x/scripts/deploy/install-xxl-job.sh
#   bash /opt/smart-converge-x/scripts/deploy/install-xxl-job.sh --skip-build   # 已有 jar 只写配置并启动
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SCX_HOME="${SCX_HOME:-/opt/smart-converge-x}"
XXL_HOME="${XXL_JOB_HOME:-/opt/xxl-job-admin}"
XXL_VERSION="${XXL_JOB_VERSION:-3.4.1}"
XXL_PORT="${XXL_JOB_PORT:-8080}"
# 源码下载：默认 Gitee 镜像（国内更快），可覆盖
XXL_SRC_URL="${XXL_JOB_SRC_URL:-https://gitee.com/xuxueli0323/xxl-job/repository/archive/v${XXL_VERSION}.tar.gz}"
XXL_SRC_URL_FALLBACK="${XXL_JOB_SRC_URL_FALLBACK:-https://github.com/xuxueli/xxl-job/archive/refs/tags/${XXL_VERSION}.tar.gz}"
SKIP_BUILD=false

for arg in "$@"; do
  case "$arg" in
    --skip-build) SKIP_BUILD=true ;;
    -h|--help)
      cat <<EOF
用法: $0 [--skip-build]

  从源码构建 xxl-job-admin ${XXL_VERSION}，写入配置，安装 systemd 并启动。
  数据库使用 /etc/scx/scx.env 中的 MYSQL_*（库内需已有 xxl_job_* 表，SCX baseline 已含）。
  访问：http://SERVER:${XXL_PORT}/xxl-job-admin   默认账号 admin / 123456
  accessToken 默认 scx-prod-xxl-token（与 application-prod.yml 一致）
EOF
      exit 0
      ;;
  esac
done

log() { printf '[%s] %s\n' "$(date '+%F %T')" "$*"; }
die() { log "ERROR: $*"; exit 1; }

[[ "$(id -u)" -eq 0 ]] || die "请使用 root 执行"

if [[ -f /etc/scx/scx.env ]]; then
  set -a
  # shellcheck disable=SC1091
  source /etc/scx/scx.env
  set +a
fi

MYSQL_HOST="${MYSQL_HOST:-mysqle379be1ffea9.rds.ivolces.com}"
MYSQL_PORT="${MYSQL_PORT:-3306}"
MYSQL_USERNAME="${MYSQL_USERNAME:-ocpxuser}"
MYSQL_PASSWORD="${MYSQL_PASSWORD:-}"
MYSQL_DATABASE="${MYSQL_DATABASE:-smart_converge_x}"
XXL_JOB_ACCESS_TOKEN="${XXL_JOB_ACCESS_TOKEN:-scx-prod-xxl-token}"
XXL_JOB_PORT="${XXL_JOB_PORT:-$XXL_PORT}"

[[ -n "$MYSQL_PASSWORD" ]] || die "MYSQL_PASSWORD 未设置，请写入 /etc/scx/scx.env"

command -v java >/dev/null 2>&1 || die "需要 JDK 17+（java）"
command -v mysql >/dev/null 2>&1 || die "需要 mysql 客户端"

mkdir -p "$XXL_HOME" /var/log/scx "$SCX_HOME"

# ---- 校验 xxl 表 ----
log "检查 MySQL 中 xxl_job 表 ..."
export MYSQL_PWD="$MYSQL_PASSWORD"
tbl_count="$(mysql --host="$MYSQL_HOST" --port="$MYSQL_PORT" --user="$MYSQL_USERNAME" \
  --batch --skip-column-names --connect-timeout=8 \
  -e "SELECT COUNT(*) FROM information_schema.tables WHERE table_schema='${MYSQL_DATABASE}' AND table_name LIKE 'xxl_job_%';" 2>&1)" \
  || die "无法连接 MySQL ${MYSQL_HOST}（检查白名单/账号）: $tbl_count"
if [[ "${tbl_count:-0}" -lt 5 ]]; then
  log "xxl_job_* 表不足，尝试导入 20xxl_job_schema.sql ..."
  schema="${SCX_HOME}/scx-backend/db/smart-converge-x/20xxl_job_schema.sql"
  [[ -f "$schema" ]] || die "缺少 $schema"
  mysql --host="$MYSQL_HOST" --port="$MYSQL_PORT" --user="$MYSQL_USERNAME" \
    "$MYSQL_DATABASE" < "$schema" || die "导入 xxl schema 失败"
  log "xxl schema 已导入"
else
  log "已存在 ${tbl_count} 张 xxl_job_* 表"
fi

# ---- 构建 / 准备 jar ----
JAR_DST="${XXL_HOME}/xxl-job-admin.jar"
if [[ "$SKIP_BUILD" == "true" && -f "$JAR_DST" ]]; then
  log "跳过构建，使用已有 $JAR_DST"
else
  command -v mvn >/dev/null 2>&1 || die "需要 Maven（mvn）以构建 xxl-job-admin"
  BUILD_ROOT="${XXL_HOME}/src"
  rm -rf "$BUILD_ROOT"
  mkdir -p "$BUILD_ROOT"
  TGZ="${XXL_HOME}/xxl-job-${XXL_VERSION}.tar.gz"
  log "下载 xxl-job ${XXL_VERSION} 源码 ..."
  if ! curl -fsSL --connect-timeout 20 --max-time 300 -o "$TGZ" "$XXL_SRC_URL"; then
    log "主源失败，尝试 GitHub ..."
    curl -fsSL --connect-timeout 20 --max-time 300 -L -o "$TGZ" "$XXL_SRC_URL_FALLBACK" \
      || die "下载 xxl-job 源码失败"
  fi
  tar -xzf "$TGZ" -C "$BUILD_ROOT" --strip-components=1 2>/dev/null \
    || tar -xzf "$TGZ" -C "$BUILD_ROOT"
  # gitee archive 可能多一层目录
  if [[ ! -f "$BUILD_ROOT/pom.xml" ]]; then
    sub="$(find "$BUILD_ROOT" -maxdepth 2 -name pom.xml | head -1)"
    [[ -n "$sub" ]] || die "解压后未找到 pom.xml"
    BUILD_ROOT="$(cd "$(dirname "$sub")" && pwd)"
  fi
  log "Maven 构建 xxl-job-admin（约数分钟）..."
  (
    cd "$BUILD_ROOT"
    mvn -pl xxl-job-admin -am -DskipTests package -q
  ) || die "Maven 构建失败"
  BUILT="$(find "$BUILD_ROOT/xxl-job-admin/target" -maxdepth 1 -name 'xxl-job-admin-*.jar' ! -name '*.original' | head -1)"
  [[ -n "$BUILT" && -f "$BUILT" ]] || die "未找到构建产物 jar"
  cp -a "$BUILT" "$JAR_DST"
  log "已安装 jar: $JAR_DST ($(du -h "$JAR_DST" | awk '{print $1}'))"
fi

# ---- 写配置（展开模板中的环境变量）----
TEMPLATE="${SCRIPT_DIR}/xxl-job/application.properties.template"
[[ -f "$TEMPLATE" ]] || TEMPLATE="${SCX_HOME}/scripts/deploy/xxl-job/application.properties.template"
[[ -f "$TEMPLATE" ]] || die "缺少配置模板"

# 模板使用 ${VAR:default} 风格不适合 envsubst；生成实际 properties
cat > "${XXL_HOME}/application.properties" <<EOF
### generated by install-xxl-job.sh $(date -Iseconds)
server.port=${XXL_JOB_PORT}
server.servlet.context-path=/xxl-job-admin

management.server.servlet.context-path=/actuator
management.health.mail.enabled=false

spring.mvc.servlet.load-on-startup=0
spring.mvc.static-path-pattern=/static/**
spring.web.resources.static-locations=classpath:/static/

spring.freemarker.templateLoaderPath=classpath:/templates/
spring.freemarker.suffix=.ftl
spring.freemarker.charset=UTF-8
spring.freemarker.request-context-attribute=request
spring.freemarker.settings.number_format=0.##########
spring.freemarker.settings.new_builtin_class_resolver=safer

mybatis.mapper-locations=classpath:/mybatis-mapper/*Mapper.xml

spring.datasource.url=jdbc:mysql://${MYSQL_HOST}:${MYSQL_PORT}/${MYSQL_DATABASE}?useUnicode=true&characterEncoding=UTF-8&autoReconnect=true&serverTimezone=Asia/Shanghai&useSSL=false&allowPublicKeyRetrieval=true
spring.datasource.username=${MYSQL_USERNAME}
spring.datasource.password=${MYSQL_PASSWORD}
spring.datasource.driver-class-name=com.mysql.cj.jdbc.Driver
spring.datasource.type=com.zaxxer.hikari.HikariDataSource
spring.datasource.hikari.minimum-idle=5
spring.datasource.hikari.maximum-pool-size=20
spring.datasource.hikari.auto-commit=true
spring.datasource.hikari.idle-timeout=30000
spring.datasource.hikari.pool-name=HikariCP
spring.datasource.hikari.max-lifetime=900000
spring.datasource.hikari.connection-timeout=10000
spring.datasource.hikari.connection-test-query=SELECT 1

xxl.job.accessToken=${XXL_JOB_ACCESS_TOKEN}
xxl.job.i18n=zh_CN
xxl.job.triggerpool.fast.max=200
xxl.job.triggerpool.slow.max=100
xxl.job.logretentiondays=30
EOF
chmod 600 "${XXL_HOME}/application.properties"
log "已写入 ${XXL_HOME}/application.properties"

# 确保 run 脚本可执行
chmod +x "${SCX_HOME}/scripts/deploy/run-xxl-job.sh" 2>/dev/null || true
chmod +x "${SCRIPT_DIR}/run-xxl-job.sh" 2>/dev/null || true

# ---- systemd ----
UNIT_SRC="${SCX_HOME}/scripts/deploy/xxl-job-admin.service"
[[ -f "$UNIT_SRC" ]] || UNIT_SRC="${SCRIPT_DIR}/xxl-job-admin.service"
cp "$UNIT_SRC" /etc/systemd/system/xxl-job-admin.service
systemctl daemon-reload
systemctl enable xxl-job-admin
systemctl restart xxl-job-admin

log "等待调度中心就绪 ..."
ok=false
for i in $(seq 1 40); do
  if curl -fsS --max-time 3 "http://127.0.0.1:${XXL_JOB_PORT}/xxl-job-admin/" >/dev/null 2>&1 \
    || curl -fsS --max-time 3 -o /dev/null -w '%{http_code}' "http://127.0.0.1:${XXL_JOB_PORT}/xxl-job-admin/toLogin" 2>/dev/null | grep -qE '200|302'; then
    ok=true
    break
  fi
  sleep 3
done

if [[ "$ok" != "true" ]]; then
  log "健康探测超时，最近日志："
  journalctl -u xxl-job-admin -n 40 --no-pager || true
  tail -40 /var/log/scx/xxl-job-admin.err.log 2>/dev/null || true
  die "xxl-job-admin 可能未成功启动，请检查日志"
fi

log "======== XXL-JOB Admin 已启动 ========"
log "URL:      http://127.0.0.1:${XXL_JOB_PORT}/xxl-job-admin"
log "公网(若安全组放行 8080): http://$(hostname -I | awk '{print $1}'):${XXL_JOB_PORT}/xxl-job-admin"
log "账号:     admin / 123456  （首次登录请改密）"
log "Token:    ${XXL_JOB_ACCESS_TOKEN}"
log "管理:     systemctl status|restart|stop xxl-job-admin"
log "一键启停: bash ${SCX_HOME}/scripts/deploy/start-xxl-job.sh {start|stop|restart|status}"
log "scx-boot 的 xxl.job.adminAddresses 应为: http://127.0.0.1:${XXL_JOB_PORT}/xxl-job-admin"
